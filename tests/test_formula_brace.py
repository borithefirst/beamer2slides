def display_page() -> list[Element]:
    page = Page()
    for text, font, size, color, box, origin in DISPLAY + BODY:
        s: RawSpan = {"id": f"p0s{len(page.spans)}", "text": text, "font": font, "size": size, "color": color,
                      "alpha": 255, "origin": list(origin), "bbox": list(box), "dir": [1.0, -0.0], "smallcaps": False}
        page.spans.append(s)
    # the braces' straight parts, either side of their tips
    page.fill(82.01, 99.87, 101.44, 101.18, BLACK)
    page.fill(111.26, 99.87, 130.69, 101.18, BLACK)
    page.fill(255.98, 113.07, 286.37, 114.38, BLUE)
    page.fill(296.19, 113.07, 326.58, 114.38, BLUE)
    return page.elements()


def test_no_brace_is_an_overlay() -> None:
    assert not [e for e in display_page() if e["kind"] == "image" and e.get("overlay")]


def test_nothing_of_the_display_is_words_but_the_label_under_it() -> None:
    els = display_page()
    text_of = {f"p0s{i}": d[0] for i, d in enumerate(DISPLAY)}
    native = [text_of[sid] for e in texts(els) for sid in e["spans"] if sid in text_of]
    assert sorted(native) == sorted(LABEL)
